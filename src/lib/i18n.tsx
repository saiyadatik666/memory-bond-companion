const DICTS: Record<LangCode, Dict> = { en, hi, as, bn, gu, mr, ta, te, kn, ml, pa, or };

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: string) => string;
  speechLocale: string;
};

const I18nContext = createContext<I18nValue | null>(null);

const STORAGE_KEY = "mb.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as LangCode | null;
    if (saved && saved in DICTS) setLangState(saved);
  }, []);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback((key: string) => DICTS[lang][key] ?? en[key] ?? key, [lang]);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t,
      speechLocale: LANGUAGES.find((l) => l.code === lang)?.speech ?? "en-IN",
    }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
